"""The fixed evaluation dataset (FR-16).

An evaluation is only worth as much as its labels, so this module is
deliberately strict about what a dataset may contain:

- **Gold labels must be human-authored.** A case says which paper and
  page answers the question, written by someone who read the paper. A
  dataset whose labels were generated by the same model being evaluated
  measures self-consistency, not quality — it will happily report that
  the system agrees with itself. Nothing in this module can enforce
  authorship, so the requirement is documented here and in the file
  format instead of being pretended at by code.
- **Pages are part of the label.** A chunk from the right paper on the
  wrong page does not contain the answer, so a paper alone is not a
  usable gold reference.
- **Datasets are versioned and hashed.** Every report records the
  dataset's ``content_hash``, so a metric change can be attributed to a
  model change or to someone editing the eval set.

Papers are referenced by ``title``, not by UUID. A checked-in dataset
has to be usable against somebody's own library, and their paper IDs
will never match the ones in this repository.
:func:`resolve_gold` maps titles to real IDs at run time and reports
every case it could not resolve, so a dataset that does not match the
library produces a clear explanation rather than quietly scoring zero.
"""

import hashlib
import json
from dataclasses import dataclass, field
from pathlib import Path
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, field_validator

# ---------------------------------------------------------------------------
# Schema
# ---------------------------------------------------------------------------


class GoldRef(BaseModel):
    """One acceptable answer location: a page of a specific paper.

    Frozen so it can live in a set: relevance is a membership test, and
    a gold reference is a value that has no business changing mid-run.
    """

    model_config = ConfigDict(frozen=True)

    paper_id: UUID
    page_number: int = Field(ge=1)


class GoldPage(BaseModel):
    """A gold page as written in the dataset: a title plus a page number.

    ``paper_id`` is filled in by :func:`resolve_gold` at run time.
    """

    paper_title: str = Field(min_length=1)
    page_number: int = Field(ge=1)
    paper_id: UUID | None = None
    note: str | None = None
    """Why this page is acceptable. Purely for humans reading a report."""


class EvalCase(BaseModel):
    """One evaluation question with its gold answer locations."""

    id: str = Field(min_length=1)
    question: str = Field(min_length=1)
    expected_pages: list[GoldPage] = Field(min_length=1)
    expected_answer_characteristics: list[str] = Field(default_factory=list)
    """What a good answer must contain, written by a human.

    Examples: "names the 2017 paper explicitly", "states a number with
    its unit", "says the method does not apply to tabular data". These
    are characteristics, not reference answers, so they describe
    properties of a good answer rather than wording to match.

    They are recorded in the report for human review and are
    deliberately **not** shown to the judge. A judge that can read what
    the answer was supposed to contain grades against the answer key
    instead of against the system's own behaviour, and every judged
    metric is defined to be answerable from the question, the retrieved
    excerpts and the generated answer alone. Leaving this empty does not
    disable judging; it only means no human expectation was recorded to
    compare the answer against afterwards.
    """

    tags: list[str] = Field(default_factory=list)
    """Free-form grouping, e.g. "exact-term" or "numeric".

    Lets a report be sliced by the kind of question, which is where
    retrieval regressions usually hide — a change that lifts paraphrased
    questions while quietly losing exact model-name lookups.
    """

    @field_validator("id")
    @classmethod
    def _slug(cls, value: str) -> str:
        cleaned = value.strip()
        if not cleaned:
            raise ValueError("case id must not be blank")
        return cleaned

    def gold_refs(self) -> set[GoldRef]:
        """Resolved gold references.

        Raises:
            ValueError: if the case was never resolved against a real
                library. Scoring an unresolved case would compare chunk
                IDs against ``None`` and report a spurious zero.
        """
        refs: set[GoldRef] = set()
        for page in self.expected_pages:
            if page.paper_id is None:
                raise ValueError(
                    f"Case {self.id!r} is unresolved: paper "
                    f"{page.paper_title!r} was not found in the library. "
                    "Run resolve_gold() before scoring."
                )
            refs.add(GoldRef(paper_id=page.paper_id, page_number=page.page_number))
        return refs

    @property
    def is_resolved(self) -> bool:
        return all(page.paper_id is not None for page in self.expected_pages)


@dataclass
class EvalDataset:
    """A loaded, validated evaluation dataset."""

    version: str
    description: str
    cases: list[EvalCase] = field(default_factory=list)
    source_path: str | None = None

    @property
    def content_hash(self) -> str:
        """SHA-256 of the canonical case content.

        Built explicitly rather than via ``model_dump(exclude=...)`` so
        the hashed fields are visible and cannot drift when the schema
        gains a field. What counts: case ids, questions, gold page
        titles and numbers, expected characteristics, tags.

        Deliberately excluded: ``note`` (prose for a human reading a
        report), ``paper_id`` (filled in by :func:`resolve_gold` from
        whichever library the run was made against, so including it would
        make one dataset hash differently for two users, and differently
        before and after resolution within a single run), and the gold
        page ordering (two acceptable pages listed in either order are
        the same case).
        """
        payload = json.dumps(
            [
                {
                    "id": case.id,
                    "question": case.question,
                    "expected_pages": sorted(
                        (page.paper_title, page.page_number)
                        for page in case.expected_pages
                    ),
                    "expected_answer_characteristics": case.expected_answer_characteristics,
                    "tags": case.tags,
                }
                for case in self.cases
            ],
            sort_keys=True,
            separators=(",", ":"),
        )
        return hashlib.sha256(payload.encode("utf-8")).hexdigest()

    def resolved_cases(self) -> list[EvalCase]:
        return [case for case in self.cases if case.is_resolved]

    def unresolved_cases(self) -> list[EvalCase]:
        return [case for case in self.cases if not case.is_resolved]

    def summary(self) -> dict:
        return {
            "version": self.version,
            "description": self.description,
            "case_count": len(self.cases),
            "resolved_count": len(self.resolved_cases()),
            "content_hash": self.content_hash,
            "tags": sorted({tag for case in self.cases for tag in case.tags}),
        }


# ---------------------------------------------------------------------------
# Loading
# ---------------------------------------------------------------------------


def load_dataset(path: str | Path) -> EvalDataset:
    """Read and validate an evaluation dataset from JSON.

    Raises:
        FileNotFoundError: if *path* does not exist.
        ValueError:       if the file is not valid JSON, or does not match
                          the dataset schema.
    """
    file_path = Path(path)
    if not file_path.exists():
        raise FileNotFoundError(f"Evaluation dataset not found: {file_path}")

    try:
        raw = json.loads(file_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ValueError(f"{file_path} is not valid JSON: {exc}") from exc

    if not isinstance(raw, dict):
        raise ValueError(f"{file_path} must contain a JSON object at the top level.")

    version = raw.get("version")
    if not version:
        raise ValueError(f"{file_path} is missing a 'version'.")

    cases_raw = raw.get("cases")
    if not isinstance(cases_raw, list) or not cases_raw:
        raise ValueError(f"{file_path} must contain a non-empty 'cases' list.")

    cases: list[EvalCase] = []
    seen_ids: set[str] = set()
    for index, case_raw in enumerate(cases_raw):
        try:
            case = EvalCase(**case_raw)
        except Exception as exc:  # noqa: BLE001
            raise ValueError(f"{file_path} case #{index} is invalid: {exc}") from exc
        if case.id in seen_ids:
            raise ValueError(
                f"{file_path} has duplicate case id {case.id!r}. "
                "Case ids must be unique so per-case scores can be compared across runs."
            )
        seen_ids.add(case.id)
        cases.append(case)

    return EvalDataset(
        version=version,
        description=raw.get("description", ""),
        cases=cases,
        source_path=str(file_path),
    )


def load_dataset_from_dict(raw: dict) -> EvalDataset:
    """Validate an in-memory dataset. Used by tests and tooling."""
    cases = [EvalCase(**case) for case in raw.get("cases", [])]
    if not cases:
        raise ValueError("Dataset must contain a non-empty 'cases' list.")
    return EvalDataset(
        version=raw.get("version", "unversioned"),
        description=raw.get("description", ""),
        cases=cases,
    )


# ---------------------------------------------------------------------------
# Resolution
# ---------------------------------------------------------------------------


def resolve_gold(
    dataset: EvalDataset,
    library_titles: dict[str, UUID],
) -> EvalDataset:
    """Fill in ``paper_id`` on every gold page from a title → ID mapping.

    Titles are matched case-insensitively and whitespace-collapsed, so a
    stray newline or capitalisation difference in a hand-edited dataset
    does not silently unresolve a case.

    Titles that match nothing are left unresolved on purpose: the caller
    reports them, and the affected cases are excluded from scoring with
    that exclusion visible in the report. Guessing a paper from a fuzzy
    title match would attach gold labels to the wrong document and
    produce confident nonsense.

    Args:
        dataset:         The dataset to resolve, in place.
        library_titles:  Mapping of paper title → paper UUID as stored in
                         the user's library.
    """
    lookup = {
        " ".join(title.split()).casefold(): paper_id
        for title, paper_id in library_titles.items()
    }

    for case in dataset.cases:
        for page in case.expected_pages:
            if page.paper_id is not None:
                continue
            key = " ".join(page.paper_title.split()).casefold()
            page.paper_id = lookup.get(key)

    return dataset
